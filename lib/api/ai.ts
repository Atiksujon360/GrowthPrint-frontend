/**
 * AI provider settings and AI-assisted actions (admin only).
 *
 * The API key is write-only: it is sent once to PUT /admin/ai/settings/api-key and the backend only ever
 * returns a masked form (••••1234). It is never stored in Redux, localStorage or sessionStorage.
 */
import { apiClient, ApiError } from './client.ts';

export type AiProvider = 'GEMINI' | 'OPENAI' | 'ANTHROPIC' | 'MISTRAL' | 'DEEPSEEK' | 'OPENAI_COMPATIBLE';

export type AiConnectionStatus =
  | 'AI_DISABLED'
  | 'NOT_CONFIGURED'
  | 'KEY_MISSING'
  | 'NOT_TESTED'
  | 'CONNECTED'
  | 'INVALID_CREDENTIALS'
  | 'UNSUPPORTED_MODEL'
  | 'RATE_LIMITED'
  | 'TIMEOUT'
  | 'PROVIDER_UNAVAILABLE'
  | 'PROVIDER_ERROR';

export interface AiProviderOption {
  id: AiProvider;
  displayName: string;
  requiresBaseUrl: boolean;
  supportsModelListing: boolean;
}

export interface AiSettings {
  enabled: boolean;
  provider: AiProvider | null;
  providerDisplayName: string | null;
  model: string | null;
  baseUrl: string | null;
  timeoutSeconds: number;
  maxOutputTokens: number;
  dailyRequestLimitPerUser: number;
  apiKeyConfigured: boolean;
  apiKeyMasked: string | null;
  encryptionConfigured: boolean;
  status: AiConnectionStatus;
  lastTestAt: string | null;
  lastTestMessage: string | null;
  updatedAt: string;
}

export interface UpdateAiSettingsInput {
  enabled: boolean;
  provider: AiProvider | null;
  model: string;
  baseUrl: string;
  timeoutSeconds: number;
  maxOutputTokens: number;
  dailyRequestLimitPerUser: number;
}

export interface SupportTriageSuggestion {
  requestId: string;
  category: 'INCLUDED_SUPPORT' | 'PAID_AD_HOC_SUPPORT' | 'NEW_PROJECT' | 'WARRANTY_OR_DEFECT_REVIEW';
  urgency: 'NORMAL' | 'URGENT';
  businessImpact: 'LOW' | 'MEDIUM' | 'CRITICAL_BLOCKER';
  summary: string;
  replyDraft: string;
  /** Always true: content generated by AI, to be reviewed by a person. */
  aiGenerated: boolean;
  provider: string;
  model: string;
  generatedAt: string;
}

/** Human text and tone for each status shown on the settings screen. */
